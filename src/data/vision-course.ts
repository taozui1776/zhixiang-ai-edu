// ========== 工具函数 ==========
function coverSlide(title: string, subtitle: string, lessonIndex: number): VisionSlide {
  return {
    slideIndex: 1,
    title,
    subtitle,
    content: `第 ${lessonIndex} 课`,
    keyPoints: [],
    illustration: '',
    type: 'cover',
  };
}

function summarySlide(points: string[], question: string): VisionSlide {
  return {
    slideIndex: 5,
    title: '本课小结',
    content: question,
    keyPoints: points,
    illustration: '',
    type: 'summary',
  };
}

