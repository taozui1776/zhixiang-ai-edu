export const SAMPLE_COURSES: ISampleCourse[] = [primaryCourse, juniorCourse, seniorCourse];

export function getSampleCourseById(id: string): ISampleCourse | undefined {
  return SAMPLE_COURSES.find((c) => c.id === id);
}

export function getSampleLessonById(lessonId: string): ISampleLesson | undefined {
  for (const course of SAMPLE_COURSES) {
    for (const unit of course.units) {
      const lesson = unit.lessons.find((l) => l.id === lessonId);
      if (lesson) return lesson;
    }
  }
  return undefined;
}
