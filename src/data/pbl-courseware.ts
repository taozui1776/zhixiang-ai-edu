// EXPORTS: ICoursewareSlide, ILessonCourseware, PBL_COURSEWARE, getCoursewareByLessonId
// 课件数据：每课时 5 页课件，每页含标题、正文、知识点、图示说明
// 数据量较大，独立文件便于维护

export interface ICoursewareSlide {
  slideIndex: number;
  title: string;
  subtitle?: string;
  content: string; // 正文内容（支持多段，用 \n\n 分隔）
  keyPoints: string[]; // 关键知识点 bullet
  illustration: string; // 图示说明（文字描述页面上的示意图/图表）
  type: 'cover' | 'knowledge' | 'case' | 'activity' | 'summary';
}

export interface ILessonExperiment {
  name: string;
  type: 'ai-lab' | 'ai-tool' | 'code-lab' | 'tool';
  targetTab?: string; // AI 实验室的实验 id 或工具 id
  description: string;
}

export interface ILessonCourseware {
  lessonId: string;
  slides: ICoursewareSlide[];
  experiments: ILessonExperiment[];
  relatedTools: string[]; // 配套工具名称
  standardPoints: string[]; // 知识点对标课标条目
}

// ========== 通用封面页工厂 ==========
function coverSlide(lessonTitle: string, project: string, lessonNo: number): ICoursewareSlide {
  return {
    slideIndex: 1,
    title: lessonTitle,
    subtitle: `${project} · 第 ${lessonNo} 课`,
    content: '',
    keyPoints: [],
    illustration: '左侧小象吉祥物手持对应主题道具，右侧大号课程标题，底部标注"智象AI通识PBL项目课"',
    type: 'cover',
  };
}

function summarySlide(keyPoints: string[], thinking: string): ICoursewareSlide {
  return {
    slideIndex: 5,
    title: '本课小结 & 拓展思考',
    content: `回顾本节课的核心知识点，想一想在生活中你还在哪里见过类似的AI应用？\n\n拓展思考：${thinking}`,
    keyPoints,
    illustration: '思维导图形式，中心是本课主题，向外辐射5个核心知识点；右下角小象举着问号气泡',
    type: 'summary',
  };
}

