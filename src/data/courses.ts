export type SchoolStage = 'primary' | 'junior' | 'senior';
export type ResourceType = '教案' | '课件' | '实验' | '作业';

export interface ILesson {
  id: string;
  title: string;
  unitId: string;
  unitTitle: string;
  stage: SchoolStage;
  grade: string;
  gradeName: string;
  lessonIndex: number;
  duration: number;
  resourceTypes: ResourceType[];
  module: string;
  objectives: string[];
  lessonPlan: {
    introduction: string;
    keyPoints: string[];
    activities: string[];
    summary: string;
  };
  courseware: {
    slides: number;
    topics: string[];
    slidesDetail?: CoursewareSlide[]; // 逐页课件详情（完整课程有此字段）
    isFull?: boolean; // 是否为完整逐页课件
  };
  experiment: {
    name: string;
    steps: string[];
    materials: string[];
    difficulty: '入门' | '进阶' | '挑战';
    relatedAiLabProjectId?: string;
  };
  homework: {
    title: string;
    description: string;
    type: '实践' | '探究' | '创作';
  };
  hardwareTips?: string[];
}

export interface CoursewareSlide {
  title: string;
  type: 'title' | 'knowledge' | 'case' | 'question' | 'practice' | 'summary';
  points: string[];
}

export interface IUnit {
  id: string;
  title: string;
  stage: SchoolStage;
  grade: string;
  gradeName: string;
  unitIndex: number;
  module: string;
  description: string;
  lessons: ILesson[];
}

export interface IGrade {
  id: string;
  name: string;
  stage: SchoolStage;
  units: IUnit[];
}

export interface IStage {
  id: SchoolStage;
  name: string;
  description: string;
  grades: IGrade[];
}

